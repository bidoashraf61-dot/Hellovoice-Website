#!/usr/bin/env python3
"""Inline the five subsetted faces as base64 @font-face rules.

No CDN link anywhere: a blocked font host fails silently to a fallback face,
and this design depends on Montserrat's geometry matching the wordmark.
Embedding removes that failure mode entirely.
"""
import base64
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "build" / "fonts"
OUT = ROOT / "site" / "assets" / "css" / "type.css"

FACES = [
    ("HV Display", "mont900.woff2", 900),
    ("HV Display", "mont800.woff2", 800),
    ("HV Text", "roboto400.woff2", 400),
    ("HV Text", "roboto500.woff2", 500),
    ("HV Text", "roboto700.woff2", 700),
]

head = """/* Hello Voice type — generated by build/make_fonts.py, do not hand-edit.
 *
 * Montserrat 800/900 (SIL OFL 1.1) and Roboto 400/500/700 (Apache 2.0), each
 * subsetted to latin + punctuation + the arrows and symbols the site uses,
 * then inlined as base64. Nothing is fetched from a font CDN: a blocked host
 * fails silently to a fallback, and the whole point of Montserrat here is that
 * its geometry matches the wordmark.
 */
"""
parts = [head]
total = 0
for family, fn, weight in FACES:
    raw = (SRC / fn).read_bytes()
    total += len(raw)
    b64 = base64.b64encode(raw).decode()
    parts.append(
        f'@font-face{{font-family:"{family}";'
        f'src:url(data:font/woff2;base64,{b64}) format("woff2");'
        f"font-weight:{weight};font-style:normal;font-display:swap}}\n")

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("".join(parts), encoding="utf-8")
print(f"{len(FACES)} faces, {total/1024:.0f}KB raw -> {OUT.stat().st_size/1024:.0f}KB css")
